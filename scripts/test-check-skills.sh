#!/usr/bin/env bash
set -euo pipefail
export LC_ALL=C

repo="$(cd "$(dirname "$0")/.." && pwd)"
checker="$repo/scripts/check-skills.sh"
tmp="$(mktemp -d "${TMPDIR:-/tmp}/test-check-skills.XXXXXX")"
trap 'rm -rf "$tmp"' EXIT
passed=0
failed=0

write_skill() {
  local dir="$1" frontmatter="$2" body="${3:-}"
  mkdir -p "$dir"
  printf -- '---\n%s\n---\n\n# %s\n%s\n' "$frontmatter" "${dir##*/}" "$body" > "$dir/SKILL.md"
}

build_clean() {
  local fx="$1"
  mkdir -p "$fx/.claude-plugin" "$fx/scripts" "$fx/agents"
  : > "$fx/scripts/link-skills.sh"

  cat > "$fx/.claude-plugin/plugin.json" <<'EOF'
{
  "name": "fixture-skills",
  "skills": [
    "./skills/engineering/alpha",
    "./skills/engineering/beta",
    "./skills/productivity/gamma"
  ],
  "agents": [
    "./agents/helper.md"
  ]
}
EOF

  cat > "$fx/README.md" <<'EOF'
# fixture

- [Engineering](skills/engineering/README.md)
- [Productivity](skills/productivity/README.md)
EOF

  write_skill "$fx/skills/engineering/alpha" 'name: alpha
description: >-
  Do alpha things. Use when the user
  asks for alpha.' '
See [beta](../beta/SKILL.md "Beta"), [usage](../beta/SKILL.md#usage), and
[gamma](<../../productivity/gamma/SKILL.md>). Notes live in
[references/notes.md](references/notes.md).

Inline `[code](missing.md)` and fenced links are skipped.

```text
[not a link](missing.md)
```

[Docs](https://example.com), [mail](mailto:a@example.com), [top](#alpha), and
[Source](SOURCE_URL) are skipped too.'
  mkdir -p "$fx/skills/engineering/alpha/references"
  echo 'Back to [alpha](../SKILL.md).' > "$fx/skills/engineering/alpha/references/notes.md"

  write_skill "$fx/skills/engineering/beta" 'name: "beta"
description: "Do beta things. Use when the user asks for beta."'

  write_skill "$fx/skills/productivity/gamma" 'name: gamma
description: Do gamma things. Use only when the user runs gamma.
disable-model-invocation: true'
  mkdir -p "$fx/skills/productivity/gamma/agents"
  cat > "$fx/skills/productivity/gamma/agents/openai.yaml" <<'EOF'
policy:
  allow_implicit_invocation: false
EOF

  write_skill "$fx/skills/deprecated/old" 'name: old
description: Retired.'

  cat > "$fx/skills/engineering/README.md" <<'EOF'
# Engineering

- [alpha](alpha/SKILL.md) does alpha things.
- [beta](beta/SKILL.md) does beta things.
EOF

  cat > "$fx/skills/productivity/README.md" <<'EOF'
# Productivity

- [gamma](gamma/SKILL.md) does gamma things.
EOF

  cat > "$fx/agents/helper.md" <<'EOF'
---
name: helper
description: Fixture agent.
---

Helps alpha. See [alpha](../skills/engineering/alpha/SKILL.md).
EOF
}

add_unrelated_installs() {
  local home="$1"
  mkdir -p "$home/.claude/skills/personal" "$home/.codex/skills" "$home/other"
  echo '---' > "$home/.claude/skills/personal/SKILL.md"
  ln -s "$home/other" "$home/.codex/skills/elsewhere"
}

install_links() {
  local home="$1" checkout="$2" dir
  mkdir -p "$home/.claude/skills" "$home/.codex/skills" "$home/.agents/skills" \
    "$home/.claude/agents" "$home/.codex/agents"
  add_unrelated_installs "$home"
  for dir in "$checkout"/skills/engineering/* "$checkout"/skills/productivity/*; do
    [ -d "$dir" ] || continue
    ln -s "$dir" "$home/.claude/skills/${dir##*/}"
    ln -s "$dir" "$home/.codex/skills/${dir##*/}"
  done
  ln -s "$checkout/agents/helper.md" "$home/.claude/agents/helper.md"
  printf '# Generated by Pixxle/skills scripts/link-skills.sh from %s\n' "$checkout/agents/helper.md" \
    > "$home/.codex/agents/helper.toml"
}

new_fixture() {
  local fx
  fx="$(mktemp -d "$tmp/case.XXXXXX")"
  cp -R "$tmp/clean/." "$fx"
  install_links "$fx.home" "$fx"
  echo "$fx"
}

# Portable in-place edit; GNU and BSD sed disagree on -i.
edit() {
  sed "$2" "$1" > "$1.new"
  mv "$1.new" "$1"
}

insert_after() {
  awk -v match_line="$2" -v new_line="$3" '{ print } $0 == match_line { print new_line }' "$1" > "$1.new"
  mv "$1.new" "$1"
}

isolated() {
  local home="$1"
  shift
  env -i PATH="$PATH" LC_ALL=C TMPDIR="$tmp" HOME="$home" \
    CLAUDE_SKILLS_DIR="$home/.claude/skills" \
    CLAUDE_AGENTS_DIR="$home/.claude/agents" \
    CODEX_HOME="$home/.codex" \
    CODEX_SKILLS_DIR="$home/.codex/skills" \
    CODEX_AGENTS_DIR="$home/.codex/agents" \
    AGENTS_SKILLS_DIR="$home/.agents/skills" \
    "$@"
}

run_checker() {
  local fx="$1"
  shift
  isolated "$fx.home" env SKILLS_REPO="$fx" bash "$checker" "$@" 2> "$fx.stderr"
}

run_linker() {
  local fx="$1" checkout="$2"
  shift 2
  cp "$repo/scripts/link-skills.sh" "$checkout/scripts/link-skills.sh"
  isolated "$fx.home" bash "$checkout/scripts/link-skills.sh" "$@" > /dev/null 2> "$fx.stderr"
}

pass() {
  passed=$((passed + 1))
  echo "ok - $1"
}

fail() {
  failed=$((failed + 1))
  echo "not ok - $1: $2"
  printf '%s\n' "$4" | cat - "$3.stderr" | sed 's/^/    /'
}

expect_clean() {
  local label="$1" fx="$2" out
  shift 2
  if out="$(run_checker "$fx" "$@")"; then
    pass "$label"
  else
    fail "$label" "expected no problems" "$fx" "$out"
  fi
}

expect_problem() {
  local label="$1" needle="$2" fx="$3" out
  shift 3
  if out="$(run_checker "$fx" "$@")"; then
    fail "$label" "expected a failure" "$fx" "$out"
    return
  fi
  if grep -qvE '^[^:]+:[0-9]+: .' <<< "$out"; then
    fail "$label" "expected only file:line: message lines" "$fx" "$out"
    return
  fi
  case "$out" in
    *"$needle"*) pass "$label" ;;
    *) fail "$label" "expected '$needle'" "$fx" "$out" ;;
  esac
}

build_clean "$tmp/clean"

fx="$(new_fixture)"
expect_clean "clean fixture passes" "$fx"
expect_clean "clean install passes --installed" "$fx" --installed

fx="$(new_fixture)"
cp -R "$fx/." "$fx.main"
rm -rf "$fx.home"
install_links "$fx.home" "$fx.main"
expect_clean "links into a second checkout pass --installed" "$fx" --installed

fx="$(new_fixture)"
rm -rf "$fx.home"
if run_linker "$fx" "$fx"; then
  expect_clean "link-skills.sh output passes --installed" "$fx" --installed
  rm -f "$fx.home/.claude/agents/helper.md"
  expect_problem "agent not installed for Claude Code" \
    "helper is not installed for Claude Code" "$fx" --installed
else
  fail "link-skills.sh output passes --installed" "link-skills.sh failed on the fixture" "$fx" ""
fi

fx="$(new_fixture)"
rm -rf "$fx.home"
if run_linker "$fx" "$fx" --claude; then
  expect_clean "link-skills.sh --claude output passes --installed --claude" "$fx" --installed --claude
  expect_problem "--installed checks Codex unless told otherwise" \
    "missing Codex skills directory" "$fx" --installed
else
  fail "link-skills.sh --claude output passes --installed --claude" "link-skills.sh failed on the fixture" "$fx" ""
fi

fx="$(new_fixture)"
rm -rf "$fx.home"
cp -R "$fx/." "$fx.gone"
if run_linker "$fx" "$fx.gone" && rm -rf "$fx.gone" && run_linker "$fx" "$fx"; then
  expect_clean "install from a removed checkout gives way to this one" "$fx" --installed
else
  fail "install from a removed checkout gives way to this one" "link-skills.sh refused the reinstall" "$fx" ""
fi

fx="$(new_fixture)"
rm -rf "$fx.home"
ln -s "$fx" "$fx.alias"
if run_linker "$fx" "$fx.alias" && run_linker "$fx" "$fx"; then
  expect_clean "install through a symlinked alias stays owned" "$fx" --installed
else
  fail "install through a symlinked alias stays owned" "link-skills.sh refused the reinstall" "$fx" ""
fi

fx="$(new_fixture)"
edit "$fx/skills/engineering/README.md" '/\[beta\]/d'
expect_problem "skill missing from its bucket README" \
  "skills/engineering/README.md:3: missing entry for beta" "$fx"

fx="$(new_fixture)"
edit "$fx/.claude-plugin/plugin.json" '/beta/d'
expect_problem "skill missing from plugin.json" \
  ".claude-plugin/plugin.json:3: missing ./skills/engineering/beta" "$fx"

fx="$(new_fixture)"
edit "$fx/.claude-plugin/plugin.json" '/helper/d'
expect_problem "agent missing from plugin.json" "missing ./agents/helper.md" "$fx"

fx="$(new_fixture)"
insert_after "$fx/.claude-plugin/plugin.json" '  "agents": [' '    "./agents/ghost.md",'
expect_problem "plugin.json entry for a removed agent" "no agent at ./agents/ghost.md" "$fx"

if python3 -I -c 'import json' > /dev/null 2>&1; then
  fx="$(new_fixture)"
  edit "$fx/.claude-plugin/plugin.json" 's|"./skills/productivity/gamma"|&,|'
  expect_problem "plugin.json with a trailing comma" "not valid JSON" "$fx"
else
  pass "plugin.json with a trailing comma # skip, no python3"
fi

fx="$(new_fixture)"
insert_after "$fx/.claude-plugin/plugin.json" '  "skills": [' '    "./skills/security/deep-review",'
expect_problem "plugin.json entry for a removed skill" \
  "no active skill at ./skills/security/deep-review" "$fx"

fx="$(new_fixture)"
insert_after "$fx/.claude-plugin/plugin.json" '  "skills": [' '    "./skills/deprecated/old",'
expect_problem "plugin.json entry for a deprecated skill" \
  "./skills/deprecated/old is deprecated" "$fx"

fx="$(new_fixture)"
edit "$fx/skills/engineering/alpha/SKILL.md" 's/^name: alpha$/name: alfa/'
expect_problem "frontmatter name mismatch" \
  "skills/engineering/alpha/SKILL.md:2: name 'alfa' does not match folder 'alpha'" "$fx"

fx="$(new_fixture)"
insert_after "$fx/skills/engineering/alpha/SKILL.md" 'name: alpha' 'allowed-tools: Read'
expect_problem "extra frontmatter key" \
  "unsupported frontmatter key 'allowed-tools'" "$fx"

fx="$(new_fixture)"
edit "$fx/skills/engineering/beta/SKILL.md" 's/^description: .*/description: ""/'
expect_problem "empty description" "description is empty" "$fx"

fx="$(new_fixture)"
mv "$fx/skills/engineering/beta/SKILL.md" "$fx/skills/engineering/beta/tmp.md"
mv "$fx/skills/engineering/beta/tmp.md" "$fx/skills/engineering/beta/skill.md"
expect_problem "lowercase skill.md" "beta/skill.md:1: rename to SKILL.md" "$fx"

fx="$(new_fixture)"
write_skill "$fx/skills/productivity/alpha" 'name: alpha
description: Shadow alpha.'
expect_problem "same skill name in two buckets" "exists in more than one bucket" "$fx"

fx="$(new_fixture)"
write_skill "$fx/skills/engineering/alpha/templates/nested" 'name: nested
description: Nested.'
expect_problem "SKILL.md nested inside a skill" "outside skills/<bucket>/<name>/" "$fx"

fx="$(new_fixture)"
edit "$fx/skills/engineering/alpha/SKILL.md" 's|(\.\./beta/SKILL.md "Beta")|(../betta/SKILL.md "Beta")|'
expect_problem "broken sibling link" "broken link '../betta/SKILL.md'" "$fx"

fx="$(new_fixture)"
echo '- [old](../deprecated/old/SKILL.md) is retired.' >> "$fx/skills/engineering/README.md"
expect_problem "bucket README links a deprecated skill" "links deprecated skills/deprecated/old/SKILL.md" "$fx"

fx="$(new_fixture)"
echo '- [old](skills/deprecated/old/SKILL.md)' >> "$fx/README.md"
expect_problem "root README links a deprecated skill" "README.md:5: links deprecated" "$fx"

fx="$(new_fixture)"
rm "$fx/skills/productivity/gamma/agents/openai.yaml"
expect_problem "disable-model-invocation without Codex policy" \
  "needs skills/productivity/gamma/agents/openai.yaml" "$fx"

fx="$(new_fixture)"
mkdir -p "$fx/skills/engineering/alpha/agents"
printf 'policy:\n  allow_implicit_invocation: false\n' > "$fx/skills/engineering/alpha/agents/openai.yaml"
expect_problem "Codex policy without disable-model-invocation" \
  "needs disable-model-invocation: true" "$fx"

fx="$(new_fixture)"
printf 'interface:\n  allow_implicit_invocation: false\n' > "$fx/skills/productivity/gamma/agents/openai.yaml"
expect_problem "Codex policy key outside policy:" \
  "set policy.allow_implicit_invocation: false" "$fx"

fx="$(new_fixture)"
echo 'Then run `gamma`.' >> "$fx/skills/engineering/beta/SKILL.md"
expect_problem "explicit-only skill named without a link" \
  "skills/engineering/beta/SKILL.md:8: names explicit-only skill gamma by bare name" "$fx"

fx="$(new_fixture)"
echo 'Run `/gamma` last, after [gamma](<../../productivity/gamma/SKILL.md>).' >> "$fx/skills/engineering/alpha/SKILL.md"
expect_problem "explicit-only skill named next to its link" \
  "names explicit-only skill gamma by bare name" "$fx"

fx="$(new_fixture)"
echo 'Then run [`gamma`](../../productivity/gamma/SKILL.md#usage).' >> "$fx/skills/engineering/beta/SKILL.md"
echo 'Run `gamma` from here.' >> "$fx/skills/productivity/gamma/SKILL.md"
expect_clean "explicit-only skill named as link text or in its own folder" "$fx"

fx="$(new_fixture)"
edit "$fx/agents/helper.md" 's/^name: helper$/name: helpr/'
expect_problem "agent name mismatch" "agents/helper.md:2: name 'helpr' does not match file 'helper'" "$fx"

fx="$(new_fixture)"
edit "$fx/agents/helper.md" 's/^description: Fixture agent\.$/description: "Fixture: agent."/'
expect_problem "agent description link-skills.sh cannot render" \
  "agents/helper.md:3: description must be a plain single-line value" "$fx"

fx="$(new_fixture)"
edit "$fx/agents/helper.md" 's/^name: helper$/name: "helper"/'
expect_problem "quoted agent name link-skills.sh rejects" \
  "agents/helper.md:2: write name: helper as a plain unquoted value" "$fx"

fx="$(new_fixture)"
edit "$fx/agents/helper.md" 's/$/\r/'
expect_problem "agent with CRLF line endings" \
  "agents/helper.md:1: write this line as a bare ---" "$fx"

fx="$(new_fixture)"
insert_after "$fx/agents/helper.md" 'name: helper' 'tools: Read'
expect_problem "agent frontmatter key the Codex role drops" \
  "unsupported agent frontmatter key 'tools'" "$fx"

fx="$(new_fixture)"
ln -s "$fx/skills/engineering/ghost" "$fx.home/.claude/skills/ghost"
expect_problem "dangling installed link" "/.claude/skills/ghost:1: dangling link" "$fx" --installed

fx="$(new_fixture)"
ln -s "$fx/skills/deprecated/old" "$fx.home/.codex/skills/old"
expect_problem "deprecated skill still installed" "old is not an active skill" "$fx" --installed

fx="$(new_fixture)"
rm "$fx.home/.claude/skills/beta"
expect_problem "active skill not installed" "beta is not installed for Claude Code" "$fx" --installed

fx="$(new_fixture)"
mkdir -p "$fx.home/.agents/skills/alpha"
echo '---' > "$fx.home/.agents/skills/alpha/SKILL.md"
expect_problem "same-named copy in the agents skills dir" "Codex also loads" "$fx" --installed

fx="$(new_fixture)"
echo 'name = "helper"' > "$fx.home/.codex/agents/helper.toml"
expect_problem "hand-written Codex agent role" "was not generated by scripts/link-skills.sh" "$fx" --installed

fx="$(new_fixture)"
ln -s "$fx/agents/ghost.md" "$fx.home/.claude/agents/ghost.md"
expect_problem "dangling Claude Code agent link" "/.claude/agents/ghost.md:1: dangling link" "$fx" --installed

fx="$(new_fixture)"
printf '# Generated by Pixxle/skills scripts/link-skills.sh from %s\n' "$fx/agents/ghost.md" \
  > "$fx.home/.codex/agents/ghost.toml"
expect_problem "Codex agent role from a removed agent" "which no longer exists, and Codex still loads it" "$fx" --installed

echo "$passed passed, $failed failed"
[ "$failed" -eq 0 ]
