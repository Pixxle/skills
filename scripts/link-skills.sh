#!/usr/bin/env bash
set -euo pipefail

physical_dir() (
  cd -P "$1" && pwd -P
)

skills_repo="$(physical_dir "$(dirname "$0")/..")"
agents_src="$skills_repo/agents"
claude_dest="${CLAUDE_SKILLS_DIR:-${HOME}/.claude/skills}"
claude_agents_dest="${CLAUDE_AGENTS_DIR:-${HOME}/.claude/agents}"
codex_root="${CODEX_HOME:-${HOME}/.codex}"
# Codex marks $CODEX_HOME/skills deprecated in favor of ~/.agents/skills but
# still reads it. ~/.agents/skills is also where npx skills installs.
codex_dest="${CODEX_SKILLS_DIR:-${codex_root}/skills}"
codex_agents_dest="${CODEX_AGENTS_DIR:-${codex_root}/agents}"
codex_marker="# Generated by Pixxle/skills scripts/link-skills.sh from "
platform="all"

usage() {
  cat <<'EOF'
Usage: scripts/link-skills.sh [--all | --claude | --codex]

  --all      Install for both Claude Code and Codex (default)
  --claude   Install for Claude Code only
  --codex    Install for Codex only

Each skills/<name> folder is symlinked into each agent's skills directory. Each
agents/<name>.md is symlinked into Claude Code's agents directory and generated
as a TOML agent role in Codex's agents directory.
Links into this repo's skills/, principles/, or agents/ that no longer reach an
active skill or agent under their own name are pruned; links that point anywhere
else are left alone.

For isolated tests or custom installations, set CLAUDE_SKILLS_DIR,
CLAUDE_AGENTS_DIR, CODEX_SKILLS_DIR, CODEX_AGENTS_DIR, or CODEX_HOME.
EOF
}

case "${1:---all}" in
  --all) platform="all" ;;
  --claude) platform="claude" ;;
  --codex) platform="codex" ;;
  --help|-h) usage; exit 0 ;;
  *) usage >&2; exit 2 ;;
esac

if [ "$#" -gt 1 ]; then
  usage >&2
  exit 2
fi

# A skill is skills/<name>/ with a SKILL.md. Newlines in skill paths are
# intentionally unsupported.
skill_dirs=()
for skill_dir in "$skills_repo"/skills/*/; do
  skill_dir="${skill_dir%/}"
  if [ -f "$skill_dir/SKILL.md" ]; then
    skill_dirs+=("$skill_dir")
  fi
done

seen_names=""
for skill_dir in ${skill_dirs[@]+"${skill_dirs[@]}"}; do
  skill_name="$(basename "$skill_dir")"
  case " $seen_names " in
    *" $skill_name "*)
      echo "ABORT: duplicate skill name '$skill_name' (found at $skill_dir)" >&2
      exit 1
      ;;
  esac
  seen_names="$seen_names $skill_name"
done

agent_files=()
if [ -d "$agents_src" ]; then
  while IFS= read -r agent_md; do
    agent_files+=("$agent_md")
  done < <(find "$agents_src" -maxdepth 1 -type f -name '*.md' -not -name README.md | sort)
fi

frontmatter_value() {
  awk -v key="$2" '
    NR == 1 { next }
    $0 == "---" { exit }
    found { if ($0 ~ /^[[:space:]]/) bad = 1; exit }
    index($0, key ":") == 1 {
      value = substr($0, length(key) + 2)
      sub(/^[[:space:]]+/, "", value)
      sub(/[[:space:]]+$/, "", value)
      found = 1
    }
    END { if (bad) exit 2; if (found) print value }
  ' "$1"
}

agent_body() {
  awk '
    in_body { if (started || $0 !~ /^[[:space:]]*$/) { started = 1; print }; next }
    NR > 1 && $0 == "---" { in_body = 1 }
  ' "$1"
}

reject_agent() {
  echo "ABORT: $1: $2" >&2
  exit 1
}

for agent_md in ${agent_files[@]+"${agent_files[@]}"}; do
  agent_name="$(basename "$agent_md" .md)"
  case "$agent_name" in
    ""|-*|*[!a-z0-9-]*) reject_agent "$agent_md" "file name must be kebab-case" ;;
  esac
  [ "$(head -n 1 "$agent_md")" = "---" ] ||
    reject_agent "$agent_md" "missing YAML frontmatter"
  fm_name="$(frontmatter_value "$agent_md" name)" ||
    reject_agent "$agent_md" "name must fit on one line"
  [ "$fm_name" = "$agent_name" ] ||
    reject_agent "$agent_md" "frontmatter name '$fm_name' must equal the file name"
  fm_description="$(frontmatter_value "$agent_md" description)" ||
    reject_agent "$agent_md" "description must be a plain single-line YAML value"
  case "$fm_description" in
    ""|[\>\|\"\'\[\{\&\*\!\%\@\`]*|*": "*|*" #"*)
      reject_agent "$agent_md" "description must be a plain single-line YAML value"
      ;;
  esac
  [ -n "$(agent_body "$agent_md" | tr -d '[:space:]')" ] ||
    reject_agent "$agent_md" "body is empty"
  if agent_body "$agent_md" | grep -q "'''"; then
    reject_agent "$agent_md" "body contains ''' which the Codex TOML cannot hold"
  fi
done

# Resolve the deepest existing ancestor of a directory path and keep the rest as
# written, so a dangling target still compares against the repo's physical path.
physical_path() {
  local head="$1" tail="" dir
  while :; do
    if dir="$(physical_dir "$head" 2>/dev/null)"; then
      printf '%s%s\n' "${dir%/}" "$tail"
      return
    fi
    case "$head" in
      ?*/*) tail="/${head##*/}$tail"; head="${head%/*}" ;;
      /*) tail="$head$tail"; head=/ ;;
      *) printf '%s\n' "$1"; return ;;
    esac
  done
}

link_target_in_physical_dir() {
  local t dir
  t="$(readlink "$1")"
  case "$t" in
    /*) ;;
    *) t="$(dirname "$1")/$t" ;;
  esac
  dir="$(physical_path "$(dirname "$t")")"
  printf '%s/%s\n' "${dir%/}" "$(basename "$t")"
}

# The paths this repo installs from, plus principles/ from an older layout. A
# link to anything else is never pruned or replaced.
is_repo_owned() {
  case "$1:$2" in
    skills:"$skills_repo"/skills/*) return 0 ;;
    skills:"$skills_repo"/principles|skills:"$skills_repo"/principles/*) return 0 ;;
    agents:"$agents_src"/*) return 0 ;;
  esac
  return 1
}

# True when a link's target is one of the sources, under the source's own name.
links_active_source() {
  local link="$1" link_target="$2" src
  shift 2
  [ "${link##*/}" = "${link_target##*/}" ] || return 1
  for src in "$@"; do
    [ "$link_target" = "$src" ] && return 0
  done
  return 1
}

guard_dest() {
  local label="$1" dest="$2" dest_target
  [ -L "$dest" ] || return 0
  dest_target="$(physical_dir "$dest" 2>/dev/null)" || dest_target="$(link_target_in_physical_dir "$dest")"
  case "$dest_target" in
    "$skills_repo"|"$skills_repo"/*)
      echo "ABORT: $label: $dest is a symlink into the repo; remove it and re-run." >&2
      return 1
      ;;
  esac
}

reclaim_dangling_link() {
  local label="$1" src="$2" target="$3"
  [ -L "$target" ] && [ ! -e "$target" ] || return 1
  ln -sfn "$src" "$target"
  echo "$label: linked $(basename "$src") -> ${src#"$skills_repo"/} (replaced a dangling link)"
  return 0
}

link_into() {
  local label="$1" dest="$2" kind="$3"
  shift 3
  local had_conflict=0 link link_target src name target current_target nested_target why

  guard_dest "$label" "$dest" || return 1
  mkdir -p "$dest"

  # Prune links into this repo that no longer reach an active source under
  # their own name: old bucket paths, old principle-* skills, deleted skills.
  for link in "$dest"/*; do
    [ -L "$link" ] || continue
    link_target="$(link_target_in_physical_dir "$link")"
    is_repo_owned "$kind" "$link_target" || continue
    links_active_source "$link" "$link_target" "$@" && continue
    why="not an active ${kind%s}"
    [ -e "$link" ] || why="dangling"
    rm -f "$link"
    echo "$label: pruned $(basename "$link") -> ${link_target#"$skills_repo"/} ($why)"
  done

  for src in "$@"; do
    name="$(basename "$src")"
    target="$dest/$name"

    reclaim_dangling_link "$label" "$src" "$target" && continue

    if [ -e "$target" ] || [ -L "$target" ]; then
      if [ -L "$target" ]; then
        current_target="$(link_target_in_physical_dir "$target")"
        if is_repo_owned "$kind" "$current_target"; then
          ln -sfn "$src" "$target"
          echo "$label: linked $name -> ${src#"$skills_repo"/}"
          continue
        fi

        # Migrate the old Codex setup, where a Codex link pointed to a Claude
        # link that in turn pointed into this repository.
        if [ -L "$current_target" ]; then
          nested_target="$(link_target_in_physical_dir "$current_target")"
          if is_repo_owned "$kind" "$nested_target"; then
            ln -sfn "$src" "$target"
            echo "$label: linked $name -> ${src#"$skills_repo"/}"
            continue
          fi
        fi
      fi

      echo "$label: skipped $name; $target is not managed by this repo" >&2
      had_conflict=1
      continue
    fi

    ln -s "$src" "$target"
    echo "$label: linked $name -> ${src#"$skills_repo"/}"
  done

  return "$had_conflict"
}

codex_role_source() {
  local first=""
  [ -f "$1" ] && [ ! -L "$1" ] || return 1
  IFS= read -r first < "$1" || [ -n "$first" ] || return 1
  case "$first" in
    "$codex_marker"*) printf '%s\n' "${first#"$codex_marker"}" ;;
    *) return 1 ;;
  esac
}

is_ours_or_orphaned_codex_role() {
  local src dir
  src="$(codex_role_source "$1")" || return 1
  [ -e "$src" ] || return 0
  dir="$(physical_dir "$(dirname "$src")" 2>/dev/null)" || return 1
  case "$dir/$(basename "$src")" in
    "$agents_src"/*.md) return 0 ;;
    *) return 1 ;;
  esac
}

codex_agent_toml() {
  local agent_md="$1" description
  description="$(frontmatter_value "$agent_md" description)"
  description="${description//\\/\\\\}"
  description="${description//\"/\\\"}"
  printf '%s%s\n' "$codex_marker" "$agent_md"
  printf '# Edit the source and re-run the script. Local edits are overwritten.\n'
  printf 'name = "%s"\n' "$(basename "$agent_md" .md)"
  printf 'description = "%s"\n' "$description"
  printf "developer_instructions = '''\n"
  agent_body "$agent_md"
  printf "'''\n"
}

# Codex discovers agent roles only as TOML files under <config-dir>/agents/, so
# each Markdown source is rendered into a role file instead of linked.
install_codex_agents() {
  local dest="$1" had_conflict=0 file src agent_md name target tmp
  shift

  guard_dest "Codex" "$dest" || return 1
  mkdir -p "$dest"

  for file in "$dest"/*.toml; do
    src="$(codex_role_source "$file")" || continue
    [ -e "$src" ] || {
      rm -f "$file"
      echo "Codex: pruned $(basename "$file") (source removed)"
    }
  done

  for agent_md in "$@"; do
    name="$(basename "$agent_md" .md)"
    target="$dest/$name.toml"

    if { [ -e "$target" ] || [ -L "$target" ]; } && ! is_ours_or_orphaned_codex_role "$target"; then
      echo "Codex: skipped $name.toml; $target is not managed by this repo" >&2
      had_conflict=1
      continue
    fi

    tmp="$(mktemp "$dest/.$name.toml.XXXXXX")" || {
      had_conflict=1
      continue
    }
    codex_agent_toml "$agent_md" > "$tmp"
    if [ -f "$target" ] && cmp -s "$tmp" "$target"; then
      rm -f "$tmp"
      echo "Codex: $name.toml up to date"
      continue
    fi
    chmod 644 "$tmp"
    mv -f "$tmp" "$target"
    echo "Codex: generated $name.toml <- ${agent_md#"$skills_repo"/}"
  done

  return "$had_conflict"
}

status=0
if [ "$platform" = "all" ] || [ "$platform" = "claude" ]; then
  link_into "Claude Code" "$claude_dest" skills ${skill_dirs[@]+"${skill_dirs[@]}"} || status=1
  link_into "Claude Code" "$claude_agents_dest" agents \
    ${agent_files[@]+"${agent_files[@]}"} || status=1
fi
if [ "$platform" = "all" ] || [ "$platform" = "codex" ]; then
  link_into "Codex" "$codex_dest" skills ${skill_dirs[@]+"${skill_dirs[@]}"} || status=1
  install_codex_agents "$codex_agents_dest" ${agent_files[@]+"${agent_files[@]}"} || status=1
fi

exit "$status"
